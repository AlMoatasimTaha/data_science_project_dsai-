"""Create and execute compact, reproducible notebooks using the real project outputs."""
import base64
from contextlib import redirect_stdout
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def markdown(text):
    return {"cell_type": "markdown", "metadata": {}, "source": text.splitlines(keepends=True)}

def code(text):
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "source": text.splitlines(keepends=True), "outputs": []}

SETUP = """from pathlib import Path
import json, sys
import pandas as pd
ROOT = Path.cwd()
if ROOT.name == 'notebooks':
    ROOT = ROOT.parent
assert ROOT.name == 'data_science_project_dsai'
sys.path.insert(0, str(ROOT / 'src'))
from jobmarket.data import load_jobs
j = load_jobs()
print('Jobs:', j.shape)
"""

def execute(name, cells, figures):
    namespace = {}
    count = 0
    for cell in cells:
        if cell["cell_type"] != "code":
            continue
        count += 1
        capture = io.StringIO()
        with redirect_stdout(capture):
            exec("".join(cell["source"]), namespace)
        cell["execution_count"] = count
        cell["outputs"] = [{"output_type": "stream", "name": "stdout", "text": capture.getvalue().splitlines(keepends=True)}]
    for fig in figures:
        path = ROOT / "reports/figures" / fig
        cells.append(markdown(f"### {fig.removesuffix('.png').replace('_',' ').title()}\n\nRegenerate with `job-market analyze`."))
        cells.append({"cell_type": "code", "metadata": {}, "execution_count": count+1,
                      "source": [f"# Figure generated by the reproducible analysis pipeline: reports/figures/{fig}\n"],
                      "outputs": [{"output_type": "display_data", "metadata": {}, "data": {"image/png": base64.b64encode(path.read_bytes()).decode(), "text/plain": [fig]}}]})
        count += 1
    nb = {"nbformat": 4, "nbformat_minor": 5, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}, "language_info": {"name": "python", "version": "3.12"}}, "cells": cells}
    for i, cell in enumerate(cells):
        cell["id"] = f"cell-{i}"
    path = ROOT / "notebooks" / name
    path.write_text(json.dumps(nb, indent=1) + "\n", encoding="utf-8")
    print(f"Executed {path.name}: {count} code cells")

